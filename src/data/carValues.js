/** Sorted list of display names for suggestions. */
export const CAR_MODELS = Object.keys(CAR_VALUES)
  .map((k) => k.replace(/\b\w/g, (c) => c.toUpperCase()))
  .sort()

/** Full year range covered by the database. */
export const CAR_YEARS = Array.from({ length: 21 }, (_, i) => 2025 - i)

/**
 * Look up a car's value by model name and year.
 * Model matching is case-insensitive.
 * Returns the value (number) or null if not found.
 */
export function lookupCarValue(model, year) {
  if (!model || !year) return null
  const key = model.trim().toLowerCase()
  const yearData = CAR_VALUES[key]
  if (!yearData) return null
  return yearData[Number(year)] ?? null
}
